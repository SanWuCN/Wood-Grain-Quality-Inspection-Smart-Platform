/* ------------------------------------------------------------------ *
 * 3. 相邻轮次拒绝样例（§10 阶段 B）
 * ------------------------------------------------------------------ */

test("§9.2 「打开工单」的歧义已消除：不得命中 ④", () => {
  /*
    工作清单原文点名了这条：
      「`打开工单` 当前会命中第④轮而不是第①轮，今晚要保留测试并消除歧义，
        建议第①轮至少同时包含'读取'和'工单'，第④轮至少同时包含'开工'和'清单'」
    下面既钉"不再命中④"，也钉"它不该被当成①"——避免有人顺手把它塞回①的触发列表
    （那会让「打开工单」这种没有读取意图的说法触发整套演示流程）。
  */
  const r = routeUtterance("小木小木，打开工单");
  if (r.kind === "script") {
    assert.notEqual(r.round.roundNo, "④", "「打开工单」不得再命中④（§9.2 要求消除歧义）");
  }
});

test("泛词单独出现不得触发任何轮次（§9.2 明令）", () => {
  /*
    §9.2：「不得把 `工单`、`天气`、`模型`、`清单`、`打开` 这类单个泛词直接映射为动作」
    注意是**单个泛词**；带动作的短语（"读取工单"）不受此限。
  */
  for (const word of ["工单", "天气", "模型", "清单", "打开", "数据", "素材"]) {
    const r = routeUtterance(`小木小木，${word}`);
    assert.equal(r.kind, "intent", `泛词「${word}」不得触发剧本`);
  }
});

test("相邻轮次不得互串（每对都要有拒绝样例）", () => {
  /*
    相邻轮最容易串，因为措辞天然接近。这里给每对一条**必须不命中对方**的样例。
    判据是"不得命中对方"，不要求走剧本——它也可能落到 intent（那也算安全）。
  */
  const pairs: [string, string, string][] = [
    /* [说法, 它应命中的轮次, 它不得命中的轮次] */
    ["读取这份工单", "①", "④"],
    ["核对开工清单", "④", "①"],
    ["近三个月天气", "②", "⑥"],
    ["检查建图和视频", "⑥", "②"],
    ["检查重建素材", "⑦", "⑥"],
    ["对比四根木柱", "⑧", "⑨"],
    ["打开Z04证据", "⑨", "⑧"],
    ["汇总采集异常", "⑫", "⑬"],
    ["拆分异常任务", "⑬", "⑫"],
    ["核对接收清单", "⑭", "⑮"],
    ["清洗这批数据", "⑮", "⑭"],
    ["对比两个模型", "⑯", "⑮"],
    ["核对目标版本", "⑰", "⑯"],
    ["雷达图像融合", "⑱", "⑲"],
    ["打开证据对照", "⑲", "⑱"],
    ["生成工单草稿", "⑳", "①"],
    ["生成任务复盘", "㉑", "⑳"],
    ["整理交付摘要", "㉒", "㉑"],
  ];
  for (const [utterance, shouldHit, mustNotHit] of pairs) {
    assertHits(`小木小木，${utterance}`, shouldHit);
    const r = routeUtterance(`小木小木，${utterance}`);
    if (r.kind === "script") {
      assert.notEqual(
        r.round.roundNo,
        mustNotHit,
        `「${utterance}」命中了相邻的 ${mustNotHit}（应命中 ${shouldHit}）`,
      );
    }
  }
});

/* ------------------------------------------------------------------ *
 * 4. ⑪ 只能由本地事件触发（§8 明文）与剧本完整性
 * ------------------------------------------------------------------ */

test("⑪ 不接受语音抢触发，来源只能是本地任务事件（§8 明文）", () => {
  const round = roundByNo("⑪");
  assert.ok(round, "⑪ 必须存在");
  assert.equal(
    round!.triggerSource,
    "local-event",
    "⑪ 的触发来源必须标为本地事件；语音不得抢触发",
  );
  /* 语音说出它的关键词也不该走剧本 */
  for (const utterance of ["巡检前检查", "巡检前检查完成", "适用性预警"]) {
    const r = routeUtterance(`小木小木，${utterance}`);
    assert.equal(r.kind, "intent", `⑪ 是主动事件，「${utterance}」不该由语音触发`);
  }
});

test("剧本仍为 22 轮，且每轮都声明了触发来源", () => {
  assert.equal(SCRIPT_ROUNDS.length, 23, "剧本 23 轮（用户 2026-09-17 定稿）");
  for (const round of SCRIPT_ROUNDS) {
    assert.ok(round.triggerSource, `第 ${round.roundNo} 轮必须声明 triggerSource`);
    if (round.triggerSource === "voice") {
      assert.ok(
        round.triggers.length >= 1,
        `第 ${round.roundNo} 轮声明了语音触发，就必须至少有一条触发短语`,
      );
      /* §8：语义短语不得只匹配单个泛词 */
      for (const t of round.triggers) {
        assert.ok(t.length >= 3, `第 ${round.roundNo} 轮的触发短语「${t}」太短，会被泛词误触`);
      }
    } else {
      assert.equal(round.triggers.length, 0, `第 ${round.roundNo} 轮非语音触发，不该登记触发短语`);
    }
  }
});
