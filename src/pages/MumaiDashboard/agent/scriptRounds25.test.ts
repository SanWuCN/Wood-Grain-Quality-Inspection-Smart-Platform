test("§9.2 「打开工单」的歧义已消除：不得命中 ③（开工清单核对）", () => {
  /*
    工作清单原文（**圈号是当时的旧编号**）：
      「`打开工单` 当前会命中第④轮而不是第①轮，今晚要保留测试并消除歧义，
        建议第①轮至少同时包含'读取'和'工单'，第④轮至少同时包含'开工'和'清单'」
    2026-09-17 重排后：旧④＝**③ 开工清单核对**，旧①＝**② 接单整理**。

    下面既钉"不再命中③"，也钉"它不该被当成②"——避免有人顺手把它塞回②的触发列表
    （那会让「打开工单」这种没有读取意图的说法触发整套演示流程）。
    判据与前缀无关：只要落了剧本就必须落对轮次。
  */
  const r = routeUtterance("小木小木，打开工单");
  if (r.kind === "script") {
    assert.notEqual(r.round.roundNo, "③", "「打开工单」不得再命中③（§9.2 要求消除歧义）");
    assert.notEqual(r.round.roundNo, "②", "「打开工单」没有读取意图，不该命中②");
  }
});

test("泛词单独出现不得触发任何轮次（§9.2 明令）", () => {
  /*
    §9.2：「不得把 `工单`、`天气`、`模型`、`清单`、`打开` 这类单个泛词直接映射为动作」
    注意是**单个泛词**；带动作的短语（"读取工单"）不受此限。
  */
  for (const word of ["工单", "天气", "模型", "清单", "打开", "数据", "素材"]) {
    const r = routeUtterance(`小木小木，${word}`);
    assert.equal(r.kind, "intent", `泛词「${word}」不得触发剧本`);
  }
});

test("易串轮次不得互串（每对都要有拒绝样例）", () => {
  /*
    措辞天然接近、或历史上被混过的轮对最容易串，这里给每对一条**必须不命中对方**的样例。
    判据是"不得命中对方"，不要求走剧本——它也可能落到 intent（那也算安全）。
    圈号一律按 2026-09-17 重排后的新编号。
  */
  const pairs: [string, string, string][] = [
    /* [说法, 它应命中的轮次, 它不得命中的轮次] */
    ["到过多少个地方巡检", "①", "②"],
    ["读取这份工单", "②", "③"],
    ["核对开工清单", "③", "②"],
    ["同步备份", "④", "③"],              /* ④ 是从 ③ 拆出来的，不得串回旧宿主 */
    ["近三个月天气", "⑤", "⑨"],
    ["同步工单任务", "⑥", "④"],           /* 都以「同步」开头 */
    ["核对数据来源", "⑦", "⑯"],           /* 都以「核对」开头 */
    ["检查建图和视频", "⑨", "⑤"],
    ["检查重建素材", "⑩", "⑨"],
    ["对比四根木柱", "⑪", "⑫"],
    ["打开Z04证据", "⑫", "⑪"],
    ["汇总采集异常", "⑭", "⑮"],
    ["拆分异常任务", "⑮", "⑭"],
    ["核对接收清单", "⑯", "⑰"],
    ["清洗这批数据", "⑰", "⑯"],
    ["跟踪现场任务状态", "⑱", "⑲"],       /* ⑱⑲ 是同段拆出的两轮 */
    ["对比两个模型", "⑲", "⑰"],
    ["对比两个模型", "⑲", "⑱"],
    ["核对目标版本", "⑳", "⑲"],
    ["雷达图像融合", "㉑", "㉒"],
    ["打开证据对照", "㉒", "㉑"],
    ["生成工单草稿", "㉓", "②"],
    ["生成任务复盘", "㉔", "㉓"],
    ["整理交付摘要", "㉕", "㉔"],
  ];
  for (const [utterance, shouldHit, mustNotHit] of pairs) {
    assertHits(`小木小木，${utterance}`, shouldHit);
    const r = routeUtterance(`小木小木，${utterance}`);
    if (r.kind === "script") {
      assert.notEqual(
        r.round.roundNo,
        mustNotHit,
        `「${utterance}」命中了易串的 ${mustNotHit}（应命中 ${shouldHit}）`,
      );
    }
  }
});

