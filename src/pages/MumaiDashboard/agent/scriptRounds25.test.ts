test("⑬ 不接受语音抢触发，来源只能是本地任务事件（§8 明文）", () => {
  /*
    ⚠ 圈号位移：这一轮在 2026-09-17 重排前是 ⑪，重排后是 **⑬ 巡检前检查（小木主动发起）**。
    判据不变 —— 它是全剧本唯一 `triggerSource: "local-event"` 的轮次。
  */
  const round = roundByNo("⑬");
  assert.ok(round, "⑬ 必须存在");
  assert.equal(
    round!.triggerSource,
    "local-event",
    "⑬ 的触发来源必须标为本地事件；语音不得抢触发",
  );
  /* 语音说出它的关键词也不该走剧本 */
  for (const utterance of ["巡检前检查", "巡检前检查完成", "适用性预警"]) {
    const r = routeUtterance(`小木小木，${utterance}`);
    assert.equal(r.kind, "intent", `⑬ 是主动事件，「${utterance}」不该由语音触发`);
  }
});

test("剧本仍为 25 轮，且每轮都声明了触发来源", () => {
  assert.equal(SCRIPT_ROUNDS.length, 25, "剧本 25 轮（用户 2026-09-17 重排定稿）");
  for (const round of SCRIPT_ROUNDS) {
    assert.ok(round.triggerSource, `第 ${round.roundNo} 轮必须声明 triggerSource`);
    if (round.triggerSource === "voice") {
      assert.ok(
        round.triggers.length >= 1,
        `第 ${round.roundNo} 轮声明了语音触发，就必须至少有一条触发短语`,
      );
      /* §8：语义短语不得只匹配单个泛词 */
      for (const t of round.triggers) {
        assert.ok(t.length >= 3, `第 ${round.roundNo} 轮的触发短语「${t}」太短，会被泛词误触`);
      }
    } else {
      assert.equal(round.triggers.length, 0, `第 ${round.roundNo} 轮非语音触发，不该登记触发短语`);
    }
  }
});
