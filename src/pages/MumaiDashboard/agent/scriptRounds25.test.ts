/** 断言：这句话必须命中指定轮次 */
function assertHits(utterance: string, expected: string) {
  const r = routeUtterance(utterance);
  assert.equal(r.kind, "script", `「${utterance}」应命中剧本（实际走 ${r.kind}）`);
  if (r.kind !== "script") return;
  assert.equal(r.round.roundNo, expected, `「${utterance}」命中了 ${r.round.roundNo}，应为 ${expected}`);
}

