/**
 * 任务范围与出发清单 —— **受控配置**（本演示的确定性整理结果）
 *
 * ⚠ 这是受控配置：改文案即改演示口径，需与《新工单红头委托与小木联动-AI交接文档
 *   v1.0》§四项任务与出发清单 / §附件未明确信息 同步。文档原话：
 *     · 「四项任务属于本演示的确定性整理结果，不允许由模型自由改写或增删」；
 *     · 「出发清单应作为代码内受控配置或服务端字段维护，不得根据图片内容临时生成」；
 *     · 「附件未明确的内容必须显示为『待现场确认』或『附件未明确』，不得补写成确定事实」。
 *
 * ── 这个模块是唯一事实源 ─────────────────────────────────────────────
 * 四项任务 / 四组装备 / 待确认项**只在这里写一遍**：展示组件只负责画（见
 * `TaskScopePanel.tsx`），测试逐字核对（见 `taskScope.test.ts`）。
 * 别处再抄一份就一定会漂移 —— 那种漂移在政府 / 文保演示里等于口径事故。
 *
 * ── 为什么是 `as const` + `Object.freeze` 两道 ───────────────────────
 *   · `as const` 让字面量类型进编译期：调用方写错字段名、想 push 一项，
 *     `npx tsc -b` 直接报错；
 *   · `Object.freeze` 管运行时：任何 `as` 绕过类型的写法也改不动，
 *     下一次读取拿到的仍是文档原文（测试会证伪这一点）。
 *   展示组件**不收任何 props 数据**（不读 API、不读工单、不读图片），
 *   从根上没有"根据现场内容临时生成清单"的入口。
 *
 * 本模块不做、也永远不会做：从图片 OCR 生成清单、按模型输出增删任务、
 * 用常识补全附件未明确的字段（防幻觉硬规则第 1 / 10 条）。
 */

export type TaskNo = 1 | 2 | 3 | 4;

export interface TaskScopeTask {
  /** 演示口径里的任务序号：1..4 连续（面板按它排序显示） */
  readonly no: TaskNo;
  readonly name: string;
  /** 逐字取自交接文档 v1.0，不得改写、不得增删 */
  readonly detail: string;
}

export interface TaskScopeKit {
  readonly group: string;
  /** 该组的装备文本，逐字取自交接文档 v1.0 */
  readonly items: string;
}

/**
 * 把数组与每个元素一起冻结。
 *
 * `Object.freeze(arr)` 只冻结数组本身，`arr[0].name = "x"` 仍然生效 ——
 * 受控配置必须连元素一起冻上，否则"改文案"只要换个写法就能绕过去。
 */
function frozen<T>(items: readonly T[]): readonly Readonly<T>[] {
  for (const item of items) Object.freeze(item);
  return Object.freeze(items);
}

