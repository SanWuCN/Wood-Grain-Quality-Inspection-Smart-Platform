/**
 * 数字孪生 · 「成果质量报告」（用户口径 2026-10-02）
 *
 * 用户原话：「作为高斯泼溅的报告，是给项目经理看的，放在数字孪生那块」。
 *
 * ── 这是什么 ────────────────────────────────────────────────────────
 * 重建成果（高斯泼溅场景）的**质量报告**，PDF、5 页，是交给项目经理的交付物。
 * 它放在数字孪生页的场景版本旁边：评审看"成果"就是"这一版场景 + 这份报告"。
 *
 * ── 为什么把地址写在这里而不是 JSX 里 ───────────────────────────────
 * 一条 URL 要在三处用到（页面的链接、静态托管、验收工装），写三份必然漂移。
 * 这里给**唯一一份**注册表，字段与文件本身对齐（文件名、大小、日期），
 * `reportPack.test.ts` 会核对"文件真的在 public/reports 里、字节数对得上"。
 *
 * ── 为什么 href 是**预编码**的 ──────────────────────────────────────
 * 文件保留中文名（用户给的原件名，`成果质量报告-text-20260914.pdf`）。
 * 浏览器对 `href` 里的非 ASCII 会自己编码，但**工装/脚本**按它取文件时
 * 容易漏掉这一步（实测：不解码的服务端会拿 `%E6%88%90…` 去磁盘上找，直接 404，
 * 服务端那侧也已按"先解码再找文件"修好了）。所以这里直接存编码后的地址，
 * 谁拿去都能用，不用各自再 encodeURIComponent 一遍。
 */

export type DeliveryReport = {
  /** 列表里给人看的名字（中文） */
  title: string;
  /** 一句话说明这是什么 */
  subtitle: string;
  /** 静态托管地址（**已编码**，可直接放进 href / fetch） */
  href: string;
  /** 原始文件名（与 public 目录里的文件逐字一致，便于人去找文件） */
  fileName: string;
  /** 给人看的字节数文案 */
  sizeText: string;
  /** 报告日期（文件名里的那一段） */
  date: string;
};

